PERSONA_MAP = {p["id"]: p for p in PERSONAS}
MODEL_CHOICES = ["deepseek-chat", "deepseek-reasoner"]


def persona_public():
    """给前端用的字段，不含系统提示词。"""
    keys = ("id", "name", "tagline", "desc", "accent", "sigil", "temperature", "greeting", "openers")
    return [{k: p[k] for k in keys} for p in PERSONAS]


def build_system_prompt(persona_id: str, custom: dict | None = None) -> str:
    """把性格 id（或自定义性格描述）拼成系统提示词。"""
    custom = custom or {}
    pid = (persona_id or "yujie").strip()
    if pid.startswith("custom:") or custom.get("name"):
        name = str(custom.get("name") or "自定义角色").strip()[:24]
        desc = str(custom.get("desc") or "").strip()[:1200]
        style = str(custom.get("style") or "").strip()[:600]
        parts = [f"你扮演「{name}」这个角色。"]
        if desc:
            parts.append(f"角色设定：{desc}")
        if style:
            parts.append(f"说话方式要求：{style}")
        parts.append(
            "在没有被明确要求改变时，始终用这个角色的口吻、措辞和态度回应，"
            "不要中途变回普通助手的语气。"
        )
        return "\n".join(parts) + "\n" + COMMON_RULES

    persona = PERSONA_MAP.get(pid) or PERSONA_MAP["yujie"]
    return persona["prompt"] + COMMON_RULES
